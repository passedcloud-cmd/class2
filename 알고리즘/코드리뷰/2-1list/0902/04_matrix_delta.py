# ------------------------------------------------------------
# 04. 델타 이동 (Delta Movement)
# ------------------------------------------------------------
# [델타] 각 방향으로 이동할 때의 '행/열 변화량'을 미리 배열로 정의해 두고,
#        반복문 하나로 인접 칸을 모두 훑는 기법. (= 방향 벡터)
#
# [핵심 3가지]
#   1) 방향을 if 문이 아니라 '데이터(리스트)'로 다룬다.
#   2) 코딩의 좌표계는 수학과 반대다. 위로 가면 행 인덱스가 -1.
#   3) 이동 후에는 반드시 경계 체크를 한다. (파이썬 음수 인덱스는 에러가 안 난다!)
# ------------------------------------------------------------

arr = [
    [1, 2, 3],
    [4, 5, 6],
    [7, 8, 9],
]
N, M = 3, 3

# 기준점: 중앙의 5
r, c = 1, 1 #1번 행의 1번 컬럼


# ------------------------------------------------------------
# 1. 델타 배열 정의 (상, 하, 좌, 우)
# ------------------------------------------------------------
# [외우지 말고 유추하기]
#   0번 줄  [ . . . ]  <- 위
#   1번 줄  [ . . . ]  <- 지금 나 (r = 1)
#   2번 줄  [ . . . ]  <- 아래
#   1번 줄에서 0번 줄(위)로 가려면? 1 -> 0 이므로 빼야 한다. 그래서 '위'는 -1.
#
#   수학 : 위로 가면 y 증가 (+1)
#   코딩 : 위로 가면 행 인덱스 감소 (-1)
#
# TODO 1) 상, 하, 좌, 우 순서로 행/열의 변화량을 채우세요.
#   힌트: 상(-1, 0) / 하(+1, 0) / 좌(0, -1) / 우(0, +1)
dr = [-1, 1, 0, 0]  # 행(row)의 변화량 : 상, 하, 좌, 우
dc = [0, 0, -1, 1]  # 열(column)의 변화량 : 상, 하, 좌, 우
# 여기선 방향키를 상하좌우로 설정했는데 다르게 설정 가능함.

direction_name = ['상', '하', '좌', '우']

print(f'기준 좌표: ({r}, {c}), 값: {arr[r][c]}')


# ------------------------------------------------------------
# 2. 방식 A - 범위 안의 좌표만 처리하기 (if 로 감싸기)
# ------------------------------------------------------------
print('\n=== 방식 A) 유효할 때만 실행 ===')
for i in range(4):
    # TODO 2) 현재 좌표 (r, c) 에 i번째 델타를 더해 다음 좌표를 구하세요.
    #   힌트: nr 은 next_row, nc 는 next_column 의 줄임말
    nr = r + dr[i]  # next_row. 다음에 이동할 방향.
    nc = c + dc[i] # next_column. 기존 위치에 방향키를 더해주는 것.

    # 경계 체크
    # TODO 3) 이동한 좌표가 배열 범위 안인지 확인하는 조건을 작성하세요.
    #   힌트: 행은 0 이상 N 미만, 열은 0 이상 M 미만이어야 한다.
    #         파이썬에서는 0 <= nr < N 처럼 이어서 쓸 수 있다.

    # 0 <= 행 < N
    # 0 <= 열 < M 이어야 함.
    if 0 <= nr < N and 0 <= nc < M:
        print(f'  {direction_name[i]} ({nr}, {nc}) -> {arr[nr][nc]}')
    else: # else 구문은 벗어났는지 확인용
        print(f'  {direction_name[i]} ({nr}, {nc}) -> 범위 벗어남')

# 음수 인덱스가 존재해선 안되기 때문에 확임.

# [기대 출력]
#   상 (0, 1) -> 2
#   하 (2, 1) -> 8
#   좌 (1, 0) -> 4
#   우 (1, 2) -> 6


# ------------------------------------------------------------
# 3. 방식 B - 범위를 벗어나면 건너뛰기 (continue)
# ------------------------------------------------------------
# 방식 A와 결과는 같다. 들여쓰기가 깊어지지 않아 탐색 코드에서 자주 쓰인다.
print('\n=== 방식 B) 벗어나면 continue ===')
for i in range(4):
    # TODO 4) 방식 A와 동일하게 다음 좌표 nr, nc 를 구하세요.
    nr = r + dr[i]
    nc = c + dc[i]

    # TODO 5) 범위를 '벗어나는' 경우라면 continue 로 건너뛰세요.
    #   힌트: 방식 A의 조건을 뒤집는다. (nr < 0 또는 nr >= N 또는 ...)
    if nr < 0 or nr >= N or nc < 0 or nc >= N:
        continue


    # TODO 6) continue 를 통과했다면 (nr, nc) 는 유효한 좌표다. 값을 출력하세요.
    #   print(f'  {direction_name[i]} ({nr}, {nc}) -> {arr[nr][nc]}')
    print(f'  {direction_name[i]} ({nr}, {nc}) -> {arr[nr][nc]}') # 실제 문제에선 print가 아니라 문제 풀이가 이어질 것


# ------------------------------------------------------------
# 4. 경계 체크를 빼먹으면 왜 위험한가? (직접 실행해서 확인)
# ------------------------------------------------------------
# 파이썬은 음수 인덱스를 '뒤에서부터'로 해석한다.
print('\n=== 경계 체크를 뺐을 때 ===')
print(f'  arr[-1][0] = {arr[-1][0]}')

# [생각해보기] arr[-1][0] 은 왜 에러가 나지 않을까? 어떤 값이 나왔는가?
#   => 에러 없이 조용히 틀린 값을 읽기 때문에, 경계 체크는 반드시 필요하다.


