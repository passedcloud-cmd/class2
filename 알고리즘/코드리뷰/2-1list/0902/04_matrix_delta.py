# TODO 7) 4방향 뒤에 대각선 4개(좌상, 우상, 좌하, 우하)를 이어붙이세요.
#   힌트: 좌상(-1, -1) / 우상(-1, +1) / 좌하(+1, -1) / 우하(+1, +1)
