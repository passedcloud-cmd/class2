# ------------------------------------------------------------
# 03. 2차원 배열 순회 (Traversal)
# ------------------------------------------------------------
# [순회] 배열의 모든 요소에 한 번씩 접근하는 것
#
# [핵심] 2중 for 문에서
#        바깥쪽 for = 천천히 도는 축(고정되는 축)
#        안쪽   for = 빨리 도는 축(움직이는 축)
#        => 무엇을 바깥에 두느냐가 '순회 순서'를 결정한다.
# ------------------------------------------------------------

arr = [
    [1, 2, 3], # 0
    [4, 5, 6], # 1
    [7, 8, 9], # N - 1위치
]
ㅆ
# TODO 0) N(행의 수), M(열의 수) 을 arr 로부터 구하세요. 숫자 3을 직접 쓰지 말 것!
#   힌트: 행의 수 = 리스트의 길이, 열의 수 = 첫 번째 행의 길이
N = len(arr)
M = len(arr[0])


# ------------------------------------------------------------
# 1. 행 우선 순회 (Row-major)
# ------------------------------------------------------------
# 바깥이 행(r) -> 한 줄을 끝까지 읽고 다음 줄로 내려간다. (책 읽는 순서)
print('=== 1. 행 우선 순회 ===')

# TODO 1) 행을 고정하고 열을 움직이는 2중 for 문을 작성하세요.
#   힌트:
#   for r in range(N):
#       for c in range(M):
#           print(arr[?][?], end=' ')
for r in range(N): # 행을 고정하고
    for c in range(M): # 열을 움직인다
        print(arr[r][c], end=' ')

print()
# [기대 출력] 1 2 3 4 5 6 7 8 9

# [손으로 추적해보기] r, c 가 어떻게 변하는지 빈칸을 채워보세요.
#   (r=0) -> (0,0)=1  (0,1)=2  (0,2)=3
#   (r=1) -> (1,0)=?  (1,1)=?  (1,2)=?
#   (r=2) -> (2,0)=?  (2,1)=?  (2,2)=?


# ------------------------------------------------------------
# 2. 역-행 우선 순회
# ------------------------------------------------------------
# 아래 행부터 위로 올라간다.
print('\n=== 2. 역-행 우선 순회 ===')

# TODO 2) 행을 마지막(N-1)부터 0까지 거꾸로 순회하도록 작성하세요.
#   힌트: range(시작, 끝, 증감) 에서 증감을 -1 로 준다.
#         끝값은 포함되지 않으므로 0까지 돌려면 끝을 -1 로 써야 한다.
#   형태: for r in range(N - 1, ?, ?):
for r in range(N - 1, -1, -1): # N-1번에서 0번까지, 거꾸로
    for c in range(M):
        print(arr[r][c], end=' ')

print()
# [기대 출력] 7 8 9 4 5 6 1 2 3


# ------------------------------------------------------------
# 3. 열 우선 순회 (Column-major)
# ------------------------------------------------------------
# 바깥이 열(c) -> 세로로 한 줄을 다 읽고 오른쪽 열로 넘어간다.
print('\n=== 3. 열 우선 순회 ===')

# TODO 3) 1번 코드에서 for 문 두 줄의 '순서만' 바꿔 작성하세요.
#   [주의] for 문의 순서만 바뀔 뿐, 값을 꺼낼 때는 여전히 arr[r][c] 다.
#          arr[c][r] 로 쓰면 완전히 다른 값을 읽게 된다.
for c in range(M): # 열 고정
    for r in range(N): # 행을 움직임
        print(arr[r][c], end=' ')


print()
# [기대 출력] 1 4 7 2 5 8 3 6 9


# ------------------------------------------------------------
# 4. 역-열 우선 순회
# ------------------------------------------------------------
print('\n=== 4. 역-열 우선 순회 ===')

# TODO 4) 열을 마지막(M-1)부터 0까지 거꾸로 순회하도록 작성하세요.
for c in range(M-1, -1, -1): # 열 고정
    for r in range(N): # 행을 움직임
        print(arr[r][c], end=' ')

print()
# [기대 출력] 3 6 9 2 5 8 1 4 7


