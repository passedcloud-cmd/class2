# 01. 2차원 배열 생성 시 주의사항
# ------------------------------------------------------------
# [핵심] 2차원 배열은 '리스트를 담은 리스트'다.
#        곱셈(*)으로 행을 늘리면 '리스트 자체'가 아니라 '리스트의 주소'가 복사된다.
# ------------------------------------------------------------

N, M = 3, 4


# ------------------------------------------------------------
# 1. [잘못된 방식] 얕은 복사 - 직접 실행해서 눈으로 확인해 보자
# ------------------------------------------------------------
# [0] * M 로 리스트 '하나'를 만든 뒤, 그 주소를 N번 복사한다.
arr_bad = [[0] * M] * N

print('=== [Bad] 초기 상태 ===')
print(arr_bad)

# 0번 행의 0번 열만 바꿔본다.
arr_bad[0][0] = 1

print('\n=== [Bad] arr_bad[0][0] = 1 실행 후 ===')
for row in arr_bad:
    print(row)

# 왜 그럴까? -> 세 행의 '주소(id)'가 전부 같기 때문
print('\n[Bad] 각 행의 id(주소) 확인')
for i in range(N):
    print(f'  arr_bad[{i}] 의 id: {id(arr_bad[i])}')

# [생각해보기] 세 행의 id 가 같다는 것은 무슨 뜻일까?
#   => 리스트가 3개가 아니라 사실상 __개 뿐이라는 뜻이다.


