"""
버블 정렬 (Bubble Sort) - 실습 스켈레톤

목표: 주석의 힌트를 보고 빈 줄(TODO)을 직접 채워 완성하기!

개념 복습
  - 인접한 두 원소를 비교해서, 앞이 더 크면 자리를 바꾼다(Swap).
  - 비유: '땅따먹기' -> 한 바퀴(Pass)를 돌 때마다 가장 큰 값이 맨 뒷자리를 확정한다.
  - 그래서 다음 바퀴에서는 확정된 뒷부분을 볼 필요가 없다!

시간 복잡도: 최악 O(n^2) / 최선 O(n) (최적화 버전)
공간 복잡도: O(1)
"""


def bubble_sort(arr):
    """기본 구현: 버블 정렬을 완성하세요."""
    n = len(arr)

    # [실습 포인트 1] 외부 반복: 정렬 범위를 뒤에서부터 하나씩 줄인다.
    #   힌트) 한 바퀴 돌 때마다 맨 뒤 한 칸이 '확정'되므로, 검사 범위 끝이 줄어든다.
    #   힌트) range(시작, 끝, 스텝) 형태로 n-1부터 1까지 역순 반복
    # TODO: for i in range(____, ____, ____):
    for i in range(n-1, 0, -1):

        # [실습 포인트 2] 내부 반복: 0번부터 i-1번까지 인접한 두 원소를 비교한다.
        #   힌트) j와 j+1을 비교할 것이므로, j의 최대값은 i-1이어야 한다.
        # TODO: for j in range(____):
        for j in range(i): # i-1번까지

            # [실습 포인트 3] 비교 조건: 오름차순이면 '앞 > 뒤'일 때 교환한다.
            #   힌트) 내림차순으로 바꾸고 싶다면 d부등호 방향만 뒤집으면 된다.
            # TODO: if ____ > ____:
            if arr[j] >arr[j + 1]:

                # [실습 포인트 4] Swap: 임시 변수(temp) 없이 튜플 언패킹으로 교환!
                #   힌트) a, b = b, a
                # TODO:
                arr[j], arr[j + 1] = arr[j + 1], arr[j]

    return arr

if __name__ == '__main__':
    # 테스트
    numbers = [64, 13, 9, 62, 3]
    print(f'정렬 전: {numbers}')
    print(f'정렬 후: {bubble_sort(numbers)}')
    # 기대 출력: 정렬 후: [3, 9, 13, 62, 64]


