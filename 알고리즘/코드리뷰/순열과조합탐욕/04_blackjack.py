# 문제
# 카지노에서 제일 인기 있는 게임 블랙잭의 규칙은 상당히 쉽다. 카드의 합이 21을 넘지 않는 한도 내에서, 카드의 합을 최대한 크게 만드는 게임이다. 블랙잭은 카지노마다 다양 한 규정이 있다.
# 한국 최고의 블랙잭 고수 김정인은 새로운 블랙잭 규칙을 만들어 상근, 창명이와 게임하려고 한다.
# 김정인 버전의 블랙잭에서 각 카드에는 양의 정수가 쓰여 있다. 그 다음, 딜러는 N의 카드를 모두 숫자가 보이도록 바닥에 놓는다. 그런 후에 딜러는 숫자 M을 크게 외친다.
# 이제 플레이어는 제한된 시간 안에 N장의 카드 중에서 3장의 카드를 골라야 한다. 블랙잭 변형 게임이기 때문에, 플레이어가 고른 카드의 합은 M을 넘지 않으면서 M과 최대한 가깝게 만들어야 한다.
# N장의 카드에 써져 있는 숫자가 주어졌을 때, M을 넘지 않으면서 M에 최대한 가까운 카드 3장의 합을 구해 출력하시오.
#
# 입력
# 첫째 줄에 카드의 개수 N(3 <= N <= 100)과 M(10 <= M <= 300,000)이 주어진다. 둘째 줄에는 카드에 쓰여 있는 수가 주어지며, 이 값은 100,000을 넘지 않는 양의 정수이다.
# 합이 M을 넘지 않는 카드 3장을 찾을 수 있는 경우만 입력으로 주어진다.
# 
# 출력
# 첫째 줄에 M을 넘지 않으면서 M에 최대한 가까운 카드 3장의 합을 출력한다.
# ============================================================
# 
# 학습 목표
#   - 문제 속에서 '순서가 상관없는 선택' 을 알아보고 조합으로 옮길 수 있다.
#   - 같은 문제를 3중 for 와 itertools 두 가지로 풀어 보고 결과가 같은지 확인한다.
#
# 입력 (04_input.txt)
#   5 21        <- 카드 5장, 합의 한도 21
#   5 6 7 8 9   <- 카드에 적힌 수
# 정답: 21 (5 + 7 + 9 또는 6 + 7 + 8)

import sys
from itertools import combinations
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent
sys.stdin = open(BASE_DIR / '04_input.txt')

N, M = map(int, input().split())
cards = list(map(int, input().split()))


# ------------------------------------------------------------
# [실습 1] 3중 for 로 풀기 (노션 2.3.1 과 같은 i < j < k 구조)
# ------------------------------------------------------------
best = 0

for i in range(N):
    for j in range(i + 1, N):
        for k in range(j + 1, N):
            total = cards[i] + cards[j] + cards[k]

            # 1-1. total 이 M 이하이면서 지금까지의 best 보다 크면 best 를 바꾸세요.
            if total <= M and total > best:  # TODO
                best = total

print(f'3중 for     : {best}   (정답 21)')


# ------------------------------------------------------------
# [실습 2] itertools.combinations 로 풀기
# ------------------------------------------------------------
best = 0

# 2-1. cards 에서 3장을 뽑는 모든 조합을 도는 for 문을 쓰세요.
#      한 번 뽑힌 3장은 튜플로 나옵니다. 합은 sum() 으로 구할 수 있습니다.
#      본문은 실습 1의 1-1 과 같습니다.
comb_result = combinations(cards, 3) # TODO
# print(comb_result) #<itertools.combinations object at 0x0000014747C914E0>
# print(list(comb_result)) # [(5, 6, 7), (5, 6, 8), (5, 6, 9), (5, 7, 8), (5, 7, 9), (5, 8, 9), (6, 7, 8), (6, 7, 9), (6, 8, 9), (7, 8, 9)]

for three in comb_result: 
    # 지금 뽑은 3개를 더한 값
    total = sum(three)

    # 지금 3개를 더한 값이 최대 M을 넘지 않으면서 현재 최대값보다 큰지 확인
    if total <= M and total > best:
        best = total


print(f'combinations: {best}   (정답 21)')
print()
print('=> 두 답이 같아야 합니다. 3장처럼 개수가 고정이면 for 로도 충분하지만,')
print('   4장, 5장으로 바뀌면 combinations 쪽은 숫자 하나만 고치면 됩니다.')
