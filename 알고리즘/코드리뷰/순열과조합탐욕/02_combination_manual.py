# 학습 목표
#   - 순열과 조합의 핵심 차이가 '다음 재귀에 넘기는 리스트' 한 줄이라는 것을 안다.
#   - 기저 조건에서 [] 가 아니라 [[]] 를 돌려줘야 하는 이유를 직접 확인한다.
#
# 노션 '순열과 조합' 2.3.2 와 같은 코드입니다.


def combination(arr, r):
    """arr 에서 r개를 뽑는 모든 조합을 2차원 리스트로 돌려줍니다."""
    # 1. 기저 조건: 더 뽑을 게 없으면 '빈 조합 하나' 를 담은 리스트를 돌려줍니다.
    #    지금은 일부러 틀린 값 [] 를 넣어 두었습니다. 이 칸은 '나중에' 고치세요.
    #    아래 2번을 먼저 채우고 실행해 보세요. 그래도 아무것도 안 나온다면 범인은 여기입니다.
    #    (노션 토글 '왜 종료 조건에서 return [[]] 를 할까?' 참고)
    if r == 0:
        return [[]]  # TODO

    result = []

    for i in range(len(arr)):
        elem = arr[i]

        # 2. elem 보다 '뒤에 있는' 원소들만 다음 재귀로 넘기세요.
        #    01번 순열은 앞뒤를 모두 넘겼습니다. 조합은 뒤만 넘깁니다.
        #    01번 permutation_r 에서 이 부분만 바꿔도 조합이 출력됩니다.
        next_arr = arr[i+1:]  # TODO

        for rest in combination(next_arr, r - 1):
            result.append([elem] + rest)

    return result


print('=== [1, 2, 3, 4] 중 3개 뽑기 ===')
for comb in combination([1, 2, 3, 4], 3):
    print(comb)
