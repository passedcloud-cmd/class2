#   텍스트 : ABABABC
#   패턴   : ABC
#   시작 0 : ABC       2글자 일치 후 불일치   (AB 까지 맞고 A != C)
#   시작 1 :  ABC      0글자 일치 후 불일치
#   시작 2 :   ABC     2글자 일치 후 불일치
#   시작 3 :    ABC    0글자 일치 후 불일치
#   시작 4 :     ABC   전부 일치! -> 정답


