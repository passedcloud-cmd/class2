# 01. Brute Force 문자열 패턴 매칭
# ------------------------------------------------------------
# [Brute Force = 고지식한 알고리즘]
#   답이 될 수 있는 모든 경우를 하나하나 다 찔러보는 방식.
#   문자열 검색이라면 "패턴이 시작될 수 있는 모든 위치"에서 한 번씩 대보는 것.
#
# [비유] 열쇠 꾸러미
#   어떤 열쇠가 맞는지 모를 때, 1번부터 마지막까지 전부 꽂아보는 것.
#   똑똑하진 않지만 열쇠가 그 안에 있다면 '반드시' 찾는다.
#
# [학습 목표]
#   포인터 두 개(i, j)를 각각 어디에 두고, 불일치가 났을 때
#   i 를 어디로 되돌릴 것인가를 설명할 수 있다.
#     i : 전체 텍스트 t 를 가리키는 인덱스
#     j : 패턴 p 를 가리키는 인덱스
# ------------------------------------------------------------

# 전체 텍스트
t = 'A pattern matching algorithm'
# 검색할 패턴
p = 'rithm'

N = len(t)  # 전체 텍스트의 길이
M = len(p)  # 찾을 패턴의 길이

# ------------------------------------------------------------
# 1. while 문 구현 (직관적 이동)
# ------------------------------------------------------------
def brute_force_while(p, t):
    '''
    고지식한 알고리즘(Brute Force) - while문 2번째 구현
    t[i]와 p[j]가 다를 경우,
    i를 (현재 i - j + 1)로 조정하고 j=0으로 되돌린 뒤 다시 비교
    '''
    i = 0
    j = 0

    while i < N and j < M:
        if t[i] != p[j]:
            # TODO 1) 불일치 시, 시작 위치를 '한 칸 뒤'로 옮기세요.
            #   힌트: 비교했던 만큼(j) 되돌아간 뒤, 거기서 한 칸 전진.
            #         구현 1과 달리 여기서는 한 줄로 끝낸다.
            i = i - j + 1

            # TODO 2) 패턴 인덱스를 처음으로 되돌리세요.
            j = 0  # <- 임시값(정답 아님). 채우기 전 무한 루프를 막는 장치
        else:
            # 일치하면 두 인덱스 모두 증가
            i += 1
            j += 1
            
    # 반복 종료 후 j값이 M이라면 패턴을 찾았다는 뜻
    if j == M:
        return i - j  # 패턴의 시작 위치 (혹은 i - M)
    else:
        return -1


print('=== 1. while 구현 (직관적 이동) ===')
print(f'  결과 인덱스: {brute_force_while(p, t)}')

print('\n' + '=' * 55 + '\n')


