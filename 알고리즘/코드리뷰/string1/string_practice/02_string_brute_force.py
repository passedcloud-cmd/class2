# [동작 과정 시각화] 포인터가 어떻게 움직이는지 눈으로 보기
# ------------------------------------------------------------
def trace_matching(p, t):
    """시작 위치마다 패턴을 대보는 과정을 그림처럼 출력"""
    n = len(t)
    m = len(p)

    print(f'  텍스트 : {t}')
    print(f'  패턴   : {p}')
    print()

    for i in range(n - m + 1):
        cnt = 0
        for j in range(m):
            if t[i + j] == p[j]:
                cnt += 1
            else:
                break

        # 패턴을 i칸 만큼 밀어서 정렬 상태를 그린다
        aligned = ' ' * i + p
        if cnt == m:
            note = '전부 일치! -> 정답'
        else:
            note = f'{cnt}글자 일치 후 불일치'

        print(f'  시작 {i} : {aligned:<{n}}  {note}')

        if cnt == m:
            break


print('=== 포인터 이동 과정 추적 ===')
trace_matching('ABC', 'ABABABC')

