# 2. for 문 구현
# ------------------------------------------------------------
def brute_force_for(p, t):
    '''
    고지식한 알고리즘(Brute Force) - for문 구현
    텍스트를 순회하며 패턴의 각 문자와 일치 여부를 확인
    '''
    # TODO 3) 패턴이 '시작될 수 있는' 모든 위치 i 를 순회하세요.
    #   힌트: t 가 10글자, p 가 3글자라면 시작 가능 위치는 0~7 (총 8곳).
    #         8 = 10 - 3 + 1. 이 +1 을 빼먹는 것이 가장 흔한 실수다.
    #   for i in range(?):
    #       cnt = 0
    #       for j in range(M):
    #           if t[i + j] == p[j]:
    #               cnt += 1
    #           else:
    #               break            # 불일치 발생 시 내부 반복 탈출
    #       if cnt == M:             # 패턴 전체가 일치
    #           return i
    for i in range(N - M + 1): #★ 패턴을 찾을 때 N - M + 1 범위는 자주 나옴
        cnt = 0
        # j: 패턴 내부를 순회하면서 매칭을 확인
        for j in range(M):
            # 만약 일치한다면
            if t[i + j] == p[j]:
                cnt += 1
            # 만약 불일치 한다면
            else:
                break # for j
        # 전체 반복이 끝나기 전에 cnt 값이 이미 M과 같다면 (패턴 길이만큼 카운트 됐다면)
        # 패턴 전체가 일치했다는 의미가 된다. 즉 다음 반복으로 넘어갈 필요가 없다.
        if cnt == M:
            return i

    # 패턴을 찾지 못한 경우
    return -1


print('=== 2. for 구현 ===')
print(f'  결과 인덱스: {brute_force_for(p, t)}')


print('\n' + '=' * 55 + '\n')


