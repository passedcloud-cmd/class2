# ------------------------------------------------------------
# [학습 목표]
#   '찾으면 바로 return' 을 '찾으면 count += 1 하고 계속' 으로 바꾸면
#   검색기가 카운터가 된다. 뼈대는 그대로, 종료 조건만 달라진다는 것을 이해한다.
# ------------------------------------------------------------


def brute_force_while_count(p, t):
    '''
    고지식한 문자열 검색(Brute Force) - while문에
    "패턴이 몇 번 등장하는지"를 세는 기능을 추가한 코드.

    - p: 패턴
    - t: 전체 텍스트
    - 반환값: p가 t 내에서 몇 번 등장하는지 나타내는 정수
    '''
    N = len(t)
    M = len(p)

    i = 0  # 텍스트 t 인덱스
    j = 0  # 패턴 p 인덱스
    count = 0  # 패턴 등장 횟수 누적

    # [주의] 조건이 i < N 뿐이다. 패턴을 찾아도 멈추지 않고 끝까지 간다.
    while i < N:
        # 만약 문자가 일치하면
        if j < M and t[i] == p[j]:
            i += 1
            j += 1

            # TODO 1) 패턴 전체를 매칭한 경우(j == M) 를 처리하세요.
            #   힌트: count 를 1 늘리고, 다음 탐색을 위해 j 를 0으로 되돌린다.
            #         (i 는 되돌리지 않는다 - 이미 확인한 구간이므로)
            if j == M:
                count += 1
                j = 0

        else:
            # 불일치 시
            i = i - j + 1  # 시작 위치를 한 칸 뒤로
            j = 0  # 패턴 인덱스 리셋

    return count


text = 'ababcabcababc'
pattern = 'abc'

result = brute_force_while_count(pattern, text)
print(f"'{pattern}' 패턴은 '{text}'에서 총 {result}번 등장")

