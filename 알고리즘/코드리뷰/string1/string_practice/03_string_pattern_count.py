def find_all_positions(p, t):
    """패턴이 등장하는 모든 시작 인덱스를 리스트로 반환 (for 문 버전)"""
    n = len(t)
    m = len(p)
    positions = []

    # TODO 2) 모든 시작 위치를 돌면서, 패턴이 전부 일치하면
    #         그 시작 인덱스를 positions 에 담으세요.
    #   03번 파일의 for 구현과 같다. 다만 return 대신 append 하고 계속 진행.
    for i in range(n - m + 1):
        cnt = 0
        for j in range(m):
            if t[i + j] == p[j]:
                cnt += 1
            else:
                break

        if cnt == m:
            positions.append(i)

    return positions


positions = find_all_positions(pattern, text)

print('=== 등장 위치 확인 ===')
print(f'  {text}')
for pos in positions:
    print(f'  {" " * pos}{pattern}  (인덱스 {pos})')
print(f'  등장 위치: {positions} -> 총 {len(positions)}번')

