# [학습 목표]
#   행 길이에 상관없이 세로로 순회하는 로직을 익힌다.
#   (SWEA 5356 '의석이의 세로로 말해요' 대비)
#
#   세로로 읽으려면 열(c)을 바깥에, 행(r)을 안쪽에 둔다.
#   단, 단어마다 길이가 다르므로 '그 칸이 존재하는지' 반드시 확인해야 한다.
# ------------------------------------------------------------

# 길이가 다른 문자열 5개
words = [
    'ABCDE', 
    'abc', 
    '012345', 
    'SSAFY', 
    'Python',
]

# TODO 1) 가장 긴 문자열의 길이(max_len)를 구하세요. (세로 순회의 최대 범위)
#   힌트: 0에서 시작해 단어를 하나씩 보며, 더 길면 갱신한다.
max_len = 0
# 방법 1
for word in words:
    if len(word) > max_len:
        max_len = len(word)

# # 방법 2
# for word in words:
#     max_len = max(max_len, len(word))
#
# # 방법 3
# max_len = max(len(word) for word in words)

print(f'최대 길이: {max_len}')
result = ''


# ------------------------------------------------------------
# 세로 읽기 (Vertical Reading)
# ------------------------------------------------------------
# TODO 2) 세로로 읽기 위한 2중 반복문을 작성하세요.
#   힌트: 열(c)이 바깥, 행(r)이 안쪽이다.
for c in range(max_len):  # 열 인덱스 (0 ~ max_len-1)
    for r in range(len(words)):  # 행 인덱스 (단어 개수)

        # TODO 3) 인덱스 에러(IndexError) 방지 조건을 작성하세요.
        #   힌트: 현재 열(c)이 그 단어(words[r])의 길이보다 작을 때만 읽어야 한다.
        #         짧은 단어에는 그 칸이 아예 없기 때문.
        # 해당 행의 단어 길이가 현재의 열 인덱스보다 길 때만 읽어야 한다.
        if c < len(words[r]):
            result += words[r][c]

print('세로 읽기 결과:', result)

# [기대 출력] Aa0SPBb1SyCc2AtD3FhE4Yo5n


print('\n' + '=' * 55 + '\n')


# ------------------------------------------------------------
# [동작 과정 시각화] 열 단위로 어떤 글자가 모이는지 보기
# ------------------------------------------------------------
print('=== 입력 단어를 격자로 보기 ===')
for w in words:
    # 짧은 단어의 빈칸은 . 으로 채워서 '구멍'을 눈에 보이게 한다
    padded = w + '.' * (max_len - len(w))
    print(f'  {padded}  ({len(w)}글자)')

print('\n=== 열마다 모이는 글자 ===')
for c in range(max_len):
    column = ''
    for r in range(len(words)):
        if c < len(words[r]):
            column += words[r][c]

    print(f'  {c}번 열 -> {column}')

