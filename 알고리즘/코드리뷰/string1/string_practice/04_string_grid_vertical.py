#   4번 열 -> E4Yo
#   5번 열 -> 5n

# [포인트] 격자 그림에서 . 으로 표시된 칸이 바로 if 문으로 건너뛰는 자리다.
#              건너뛰는 자리다. 이 조건이 없으면 몇 번 열부터 에러가 날까? ==> 이 조건이 없으면 2번 열부터 IndexError 가 터진다.


