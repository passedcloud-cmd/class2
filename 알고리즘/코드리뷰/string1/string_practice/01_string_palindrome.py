# ------------------------------------------------------------
# 01. 회문 판별 (Palindrome)
# ------------------------------------------------------------
# [회문] 앞에서 읽으나 뒤에서 읽으나 같은 단어 (level, 기러기, 토마토)
#
# [학습 목표]
#   s == s[::-1] 뿐만 아니라, 인덱스를 조작하여 직접 비교하는 법을 익힌다.
#   양 끝에서 안쪽으로 좁혀올 때 i 의 짝이 왜 N - 1 - i 인지 설명할 수 있다.
# ------------------------------------------------------------

word = 'level'
N = len(word)

print(f'테스트 단어: {word}')


# ------------------------------------------------------------
# 1. Pythonic Way (슬라이싱 활용)
# ------------------------------------------------------------
# TODO 1) 슬라이싱으로 문자열을 뒤집어 원본과 같은지 판별하세요.
#   힌트: 문자열을 통째로 뒤집는 슬라이싱은 [::-1]
if word == word[::-1]:
    print('[1] 회문입니다 (Slicing)')
else:
    print('[1] 회문이 아닙니다 (Slicing)')


# ------------------------------------------------------------
# 2. Algorithmic Way (인덱스 활용) - 중요
# ------------------------------------------------------------
# 양 끝에서 안쪽으로 좁혀오며 비교
is_palindrome = True

# TODO 2) 몇 번만 비교하면 충분할까? 반복 횟수를 채우세요.
#   힌트: 앞뒤를 짝지어 보므로 전체 길이의 절반이면 된다.
#         길이가 홀수면 가운데 글자는 비교할 필요가 없다 (자기 자신과 비교).
#         정수 나눗셈은 // 를 쓴다.
for i in range(N // 2):
    # TODO 3) word[i] 와 짝이 되는 '뒤쪽 문자'를 비교하세요.
    #   힌트: 마지막 인덱스는 N 이 아니라 N - 1 이다.
    #         i = 0 일 때 짝은 마지막, i = 1 일 때 짝은 마지막 - 1 ...
    if word[i] != word[N - 1 - i]:
        is_palindrome = False
        break

if is_palindrome:
    print('[2] 회문입니다 (Index Loop)')
else:
    print('[2] 회문이 아닙니다 (Index Loop)')

# [기대 출력] level 은 회문이므로 두 줄 모두 '회문입니다'
#
# [주의] TODO 2 를 채우기 전에는 반복문이 한 번도 돌지 않아서
#        is_palindrome 이 True 인 채로 남아 무조건 '회문입니다' 가 찍힌다.
#        여기에 속지 말 것. 'python' 같은 회문이 아닌 단어로도 꼭 확인하자.


print('\n' + '=' * 55 + '\n')


# ------------------------------------------------------------
# [동작 과정 시각화] 어떤 짝끼리 비교되는지 눈으로 보기
# ------------------------------------------------------------
def trace_palindrome(word):
    """양 끝에서 좁혀오는 비교 과정을 출력"""
    n = len(word)
    print(f'  단어: {word}  (길이 {n})')

    for i in range(n // 2):
        # TODO 4) 뒤쪽 인덱스를 구하세요. (위 TODO 3 과 같은 공식)
        back = n - 1 - i

        mark = '일치' if word[i] == word[back] else '불일치 -> 회문 아님'
        print(f'  비교 {i + 1}: word[{i}]={word[i]!r} <-> word[{back}]={word[back]!r}  {mark}')

        if word[i] != word[back]:
            return

    print('  모든 짝이 일치 -> 회문')


print('=== 비교 과정 추적 ===')
trace_palindrome('level')
print()
trace_palindrome('python')

# [기대 출력]
#   level  : word[0]='l' <-> word[4]='l' 일치, word[1]='e' <-> word[3]='e' 일치
#   python : word[0]='p' <-> word[5]='n' 불일치


print('\n' + '=' * 55 + '\n')


