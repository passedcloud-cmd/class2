# [문제]
#   여러 종류의 괄호 ( ), [ ], { } 와 숫자가 섞인 문자열이 주어질 때
#   괄호 짝이 올바른지 검사한다. 맞으면 1, 아니면 -1 을 출력한다.
#   숫자나 기타 문자는 검사에 영향을 주지 않는다.
#
# [짝이 맞는다는 것은?]
#   1. 여는 괄호와 닫는 괄호의 개수가 같아야 한다.
#   2. 같은 종류끼리 짝이 맞아야 한다.        ( ] 는 잘못됨
#   3. 올바르게 중첩되어야 한다.              ( [ ) ] 는 잘못됨
#
# [학습 목표]
#   "가장 마지막에 연 괄호를 가장 먼저 닫아야 한다" 가 왜 LIFO 인지 이해하고,
#   여는 괄호 push / 닫는 괄호 pop 패턴을 직접 구현한다.
#
# [알고리즘]
#   1. 한 글자씩 읽는다.
#   2. 여는 괄호 -> push (나중에 짝을 맞추려고 보관)
#   3. 닫는 괄호 -> pop 해서 같은 종류인지 확인
#        - 스택이 비어 꺼낼 게 없거나, 종류가 다르면 실패
#   4. 끝까지 읽었을 때 스택이 텅 비어야 성공 (남아있으면 여는 괄호 과다)
# ------------------------------------------------------------

import sys
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent
sys.stdin = open(BASE_DIR / 'input.txt')


def check_brackets(string):
    stack = []

    for char in string:
        # -------------------------------------------------
        # 여는 괄호 처리
        # -------------------------------------------------
        # 문자열 '([{' 안에 char 가 포함되어 있다면 여는 괄호다.
        if char in '([{':
            # TODO 1) 여는 괄호는 나중에 짝을 맞추기 위해 스택에 넣으세요(push).
            stack.append(char)

        # -------------------------------------------------
        # 닫는 괄호 처리
        # -------------------------------------------------
        # 문자열 ')]}' 안에 char 가 포함되어 있다면 닫는 괄호다.
        elif char in ')]}':

            # TODO 2) 닫는 괄호가 나왔는데 스택이 비어있다면? (여는 괄호 부족)
            #   힌트: 스택의 길이를 확인해 비어있으면 -1 을 반환
            if len(stack) == 0:
                return -1

            # TODO 3) 스택에서 가장 최근에 넣은 여는 괄호를 꺼내세요(pop).
            open_char = stack.pop()

            # -- 소괄호 짝 검사 (이 줄은 예시로 채워져 있습니다)
            if char == ')' and open_char != '(':
                return -1

            # TODO 4) 대괄호 짝 검사: 현재 문자가 ']' 인데 꺼낸 문자가 '[' 가 아니라면?
            elif char == ']' and open_char != '[':
                return -1

            # TODO 5) 중괄호 짝 검사: 현재 문자가 '}' 인데 꺼낸 문자가 '{' 가 아니라면?
            elif char == '}' and open_char != '{':
                return -1

            # 해당 짝 검사 코드는 이렇게 작성하는 것을 권장한다
            # 이유: 세 개의 elif 가지가 전부 똑같은 일(return -1)만 하고 있으니, 조건들을 or로 하나로 합침
            # 이유: and가 or보다 우선순위가 높아서 괄호 없이 써도 동작은 같지만, 가독성을 위해 괄호를 써줌
            # if (
            #     (char == ')' and open_char != '(')
            #     or (char == ']' and open_char != '[')
            #     or (char == '}' and open_char != '{')
            # ):
            #     return -1


        # 괄호가 아닌 다른 문자(숫자 등)는 그냥 넘어간다.
        else:
            continue

    # -------------------------------------------------
    # 최종 결과 판별
    # -------------------------------------------------
    # TODO 6) 반복문이 끝났을 때 스택이 비어있어야 성공이다.
    #   힌트: 남아있다면 여는 괄호가 더 많다는 뜻 -> 실패
    if len(stack) == 0:
        return 1  # 성공 (깔끔하게 비어있음)
    else:
        return -1  # 실패 (잔여물 있음)


T = int(input())
for tc in range(1, T + 1):
    line = input()
    print(f'#{tc} {check_brackets(line)}')

