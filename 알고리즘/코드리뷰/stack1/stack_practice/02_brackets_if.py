# [동작 과정 시각화] 스택이 어떻게 쌓이고 빠지는지 추적
# ------------------------------------------------------------
def trace_brackets(string):
    """글자를 하나씩 읽으며 스택 상태 변화를 출력"""
    stack = []
    pairs = {')': '(', ']': '[', '}': '{'}
    print(f'  검사 문자열: {string}')

    for idx, char in enumerate(string):
        if char in '([{':
            stack.append(char)
            print(f'  [{idx}] {char!r} 여는 괄호 -> push   스택: {stack}')

        elif char in ')]}':
            if len(stack) == 0:
                print(f'  [{idx}] {char!r} 닫는 괄호 -> 스택이 비어 꺼낼 수 없음 => 실패')
                return -1

            open_char = stack.pop()

            if pairs[char] != open_char:
                print(
                    f'  [{idx}] {char!r} 닫는 괄호 -> pop {open_char!r} '
                    f'(기대: {pairs[char]!r}) 종류 불일치 => 실패'
                )
                return -1

            print(f'  [{idx}] {char!r} 닫는 괄호 -> pop {open_char!r} 짝 맞음   스택: {stack}')

    if len(stack) == 0:
        print('  끝까지 읽었고 스택이 비어 있음 => 성공')
        return 1

    print(f'  끝까지 읽었으나 스택에 {stack} 남음 (여는 괄호 과다) => 실패')
    return -1


