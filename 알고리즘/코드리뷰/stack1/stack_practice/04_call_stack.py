import sys


# ------------------------------------------------------------
# 1. 기본 예시 - 출력 순서로 LIFO 확인하기
# ------------------------------------------------------------
def func2():
    print('함수 2 시작')
    print('함수 2 종료')


def func1():
    print('함수 1 시작')
    func2()
    print('함수 1 종료')


print('=== 기본 예시 ===')
print('메인 시작')
func1()
print('메인 끝')

# [실행 전에 예측해 보기] 아래 6줄의 순서를 먼저 종이에 적어 본 뒤 실행하자.
#   메인 시작 / 함수 1 시작 / 함수 2 시작 / 함수 2 종료 / 함수 1 종료 / 메인 끝
#
# [생각해보기] '함수 1 종료' 는 왜 '함수 2 종료' 보다 뒤에 찍힐까?
#              시작 순서는 1 -> 2 인데, 종료 순서는 2 -> 1 이다.


print('\n' + '=' * 55 + '\n')


# ------------------------------------------------------------
# [동작 과정 시각화] 호출 스택을 직접 흉내내어 그려보기
# ------------------------------------------------------------
# 파이썬이 내부적으로 하는 일을 리스트 하나로 따라해 본다.
call_stack = []


def enter(name):
    """함수에 들어갈 때 호출 스택에 push"""
    call_stack.append(name)

    depth = len(call_stack) - 1
    print(f'{"  " * depth}-> {name} 호출   [스택: {call_stack}]')


def leave(name):
    """함수가 끝날 때 호출 스택에서 pop"""
    call_stack.pop()

    depth = len(call_stack)
    print(f'{"  " * depth}<- {name} 종료   [스택: {call_stack}]')


def traced_func2():
    enter('func2')
    leave('func2')


def traced_func1():
    enter('func1')
    traced_func2()
    leave('func1')


# [읽어보기] 이 추적 코드는 완성되어 있습니다.
#            실행 결과의 들여쓰기 깊이가 곧 스택의 높이입니다.

print('=== 호출 스택 추적 ===')
enter('main')
traced_func1()
leave('main')

# [기대 출력]
#   -> main 호출      [스택: ['main']]
#     -> func1 호출   [스택: ['main', 'func1']]
#       -> func2 호출 [스택: ['main', 'func1', 'func2']]
#       <- func2 종료 [스택: ['main', 'func1']]
#     <- func1 종료   [스택: ['main']]
#   <- main 종료      [스택: []]
#
# [포인트] 들여쓰기 깊이 = 스택의 높이. 안쪽부터 차례로 빠져나온다.


print('\n' + '=' * 55 + '\n')


