#   함수가 호출되면 그 함수의 정보(스택 프레임)가 스택에 쌓이고(push),
#   함수가 끝나면 스택에서 빠진다(pop).
#   => 가장 마지막에 호출된 함수가 가장 먼저 끝난다. (LIFO)
#
