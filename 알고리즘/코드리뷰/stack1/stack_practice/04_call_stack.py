# [기대 출력] 호출은 5,4,3,2,1 순서지만 종료는 1,2,3,4,5 순서다.
#             재귀 함수의 "돌아오는 길" 이 바로 스택이 pop 되는 과정이다.

print()
print('=== 종료 조건이 없으면? ===')


def infinite_recursion(n):
    """일부러 종료 조건을 뺀 함수"""
    return infinite_recursion(n + 1)


try:
    infinite_recursion(0)
except RecursionError:
    print('  RecursionError 발생! 호출 스택이 가득 찼다 (스택 오버플로)')
    print(f'  파이썬의 기본 재귀 한도: {sys.getrecursionlimit()}')
    print('  => 종료 조건(base case) 을 반드시 만들어야 하는 이유다.')


