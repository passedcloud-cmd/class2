# 02. 선택 정렬의 의미와 한계
# ------------------------------------------------------------
# [핵심] 선택 정렬은 '이미 정렬된 데이터'에서도 전혀 빨라지지 않는다.
#        최솟값을 찾으려면 남은 구간을 무조건 끝까지 봐야 하기 때문이다.
#        => 데이터 상태와 무관하게 비교 횟수가 항상 똑같다. (O(n^2))
# ------------------------------------------------------------


def selection_sort_counting(arr):
    """비교 횟수와 교환 횟수를 세면서 정렬하는 버전"""
    n = len(arr)
    compare_count = 0
    swap_count = 0

    for i in range(n - 1):
        min_idx = i

        for j in range(i + 1, n):
            # TODO 1) 비교가 일어날 때마다 compare_count 를 1 증가시키세요.
            #   힌트: if 문 '안'이 아니라 '앞'에 두어야 한다.
            #         조건이 참이든 거짓이든 비교 자체는 이미 일어났기 때문.
            compare_count += 1  # 비교는 무조건 일어난다
            if arr[j] < arr[min_idx]:
                min_idx = j

        # TODO 2) 최솟값을 i번 자리로 교환하고, swap_count 를 1 증가시키세요.
        #   힌트: min_idx 가 i 그대로라면 자기 자신과 바꾸는 셈이라 값이 움직이지 않는다.
        #         이런 '제자리 교환'까지 세면 데이터 상태와 무관하게 항상 n-1 회가 나온다.
        if min_idx != i:
            arr[i], arr[min_idx] = arr[min_idx], arr[i]
            swap_count += 1

    return compare_count, swap_count


# ------------------------------------------------------------
# 1. 데이터 상태를 바꿔가며 비교 횟수 확인하기
# ------------------------------------------------------------
best_case = [1, 2, 3, 4, 5, 6, 7, 8]  # 이미 정렬된 상태
worst_case = [8, 7, 6, 5, 4, 3, 2, 1]  # 완전히 역순
random_case = [3, 8, 1, 7, 2, 6, 4, 5]  # 뒤죽박죽

print('=== 데이터 상태별 비교 횟수 ===')
for name, data in [
    ('이미 정렬됨', best_case),
    ('완전 역순  ', worst_case),
    ('뒤죽박죽  ', random_case),
]:
    # data[:] 는 원본을 건드리지 않기 위한 '복사본' 이다.
    compare_count, swap_count = selection_sort_counting(data[:])
    print(f'  {name} : 비교 {compare_count}회, 교환 {swap_count}회')

