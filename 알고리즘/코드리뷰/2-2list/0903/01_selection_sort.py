#     (힌트: 선택 정렬은 회차당 교환이 몇 번인가?)
#
# Q4. 외부 반복이 range(n) 이 아니라 range(n - 1) 인 이유는?
#
# Q5. 아래 두 코드는 왜 결과가 다를까? 직접 실행해서 확인해 보자.
#       (A) arr[i], arr[min_idx] = arr[min_idx], arr[i]
#       (B) arr[i] = arr[min_idx]
#           arr[min_idx] = arr[i]

# ------------------------------------------------------------
# [점검 답변: 흔한 실수 & 디버깅 팁]
# ------------------------------------------------------------
# 1) 인덱스가 아니라 '값'을 저장하는 실수
#      min_value = arr[i]   (X)  -> 나중에 어디랑 바꿔야 할지 알 수 없다
#      min_idx = i          (O)  -> 위치를 알아야 교환할 수 있다
#
# 2) 내부 반복을 range(i, n) 으로 쓰는 실수
#      이미 min_idx = i 로 가정했으므로 자기 자신과 또 비교하는 낭비가 생긴다.
#      틀린 답이 나오진 않지만 range(i + 1, n) 이 정확한 표현이다.
#
# 3) 찾는 도중에 교환해 버리는 실수
#      for j 안에서 바로 swap 하면 선택 정렬이 아니라 다른 알고리즘이 된다.
#      => "다 찾고 나서, 회차당 딱 한 번만 교환" 이 선택 정렬의 정체성이다.
#
# 4) 외부 반복을 range(n) 으로 쓰기
#      마지막 원소는 이미 제자리이므로 range(n - 1) 이면 충분하다.
#      (range(n) 이어도 결과는 같지만, 왜 n-1 인지 설명할 수 있어야 한다)
#
# 5) 교환 구문을 두 줄로 쪼개는 실수
#      arr[i] = arr[min_idx]        (X) 원래 arr[i] 값이 사라진다
#      arr[min_idx] = arr[i]
#      arr[i], arr[min_idx] = arr[min_idx], arr[i]   (O) 파이썬 동시 할당
