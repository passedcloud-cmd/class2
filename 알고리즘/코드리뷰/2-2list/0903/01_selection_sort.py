# 01. 선택 정렬 (Selection Sort)
# ------------------------------------------------------------
# [비유] 키 순서대로 줄 세우기
#   1) 아직 줄을 서지 않은 사람들 중에서 가장 키가 작은 사람을 찾는다.
#   2) 그 사람을 줄의 맨 앞자리로 보낸다.
#   3) 이미 줄을 선 사람은 제외하고, 나머지 중에서 다시 가장 작은 사람을 찾는다.
#   4) 모든 사람이 줄을 설 때까지 반복한다.
#
# [핵심] '값'이 아니라 '최솟값의 인덱스(min_idx)'를 찾는다.
#        찾는 동안에는 아무것도 옮기지 않고, 다 찾은 뒤 딱 한 번만 교환한다.
# ------------------------------------------------------------


def selection_sort(arr):
    """
    선택 정렬 (Selection Sort):
    - 매 회차마다 '남은 구간'에서 최솟값을 '선택'하여 정해진 위치로 옮기는 방식
    - 시간 복잡도: O(n^2)
    """
    n = len(arr)

    # [외부 반복] 정렬할 위치(i)를 하나씩 결정해 나갑니다.
    # 마지막 원소 하나가 남았을 때는 이미 정렬된 상태이므로 n-1번만 반복합니다.
    for i in range(n - 1):

        # TODO 1) 현재 보고 있는 위치(i)를 '최솟값의 위치'라고 일단 가정하세요.
        #   힌트: 값이 아니라 '인덱스'를 담아야 나중에 교환할 수 있다.
        min_idx = i

        # TODO 2) [내부 반복] 아직 정렬되지 않은 구간(i+1 ~ 끝)을 탐색하며
        #         진짜 최솟값의 인덱스를 찾아 min_idx 를 갱신하세요.
        #   힌트: for j in range(?, ?):
        #             if arr[j] < arr[min_idx]:
        #                 min_idx = ?
        for j in range(i + 1, n):
            # 현재 가정된 최솟값보다 더 작은 값을 발견한다면?
            if arr[j] < arr[min_idx]:
                # j가 진짜 최솟값의 인덱스임. 위치를 갱신
                min_idx = j


        # TODO 3) [교환] 탐색이 끝난 뒤, 최솟값을 현재 자리(i)로 가져오세요.
        #   힌트: 파이썬은 a, b = b, a 로 두 값을 한 번에 맞바꿀 수 있다.
        #         두 줄로 나눠 쓰면 원래 값이 덮어써져서 사라진다!
        arr[i], arr[min_idx] = arr[min_idx], arr[i]


# --- 실행 및 검증 ---
numbers = [2, 5, 1, 3, 4]
print(f'정렬 전: {numbers}')

selection_sort(numbers)

print(f'정렬 후: {numbers}')

# [기대 출력]
#   정렬 전: [2, 5, 1, 3, 4]
#   정렬 후: [1, 2, 3, 4, 5]


print('\n' + '=' * 55 + '\n')


# ------------------------------------------------------------
# [동작 과정 시각화] 회차마다 무슨 일이 일어나는지 눈으로 보기
# ------------------------------------------------------------
def selection_sort_verbose(arr):
    """회차별 상태 변화를 출력하는 학습용 버전"""
    n = len(arr)

    print(f'시작    : {arr}')

    for i in range(n - 1):
        min_idx = i

        for j in range(i + 1, n):
            if arr[j] < arr[min_idx]:
                min_idx = j

        # 확정된 구간(sorted) | 탐색 구간(unsorted) 을 구분해서 보여준다
        sorted_part = arr[:i]
        target = arr[i]
        found = arr[min_idx]

        arr[i], arr[min_idx] = arr[min_idx], arr[i]

        print(
            f'Pass {i + 1} : 남은 구간에서 최솟값 {found}(인덱스 {min_idx}) 선택 '
            f'-> {i}번 자리의 {target} 와 교환'
        )
        print(f'         {arr}   (확정: {sorted_part + [found]})')


print('=== 회차별 동작 과정 ===')
selection_sort_verbose([2, 5, 1, 3, 4])

# [기대 출력]
#   시작    : [2, 5, 1, 3, 4]
#   Pass 1 : [1, 5, 2, 3, 4]   <- 1의 위치 확정
#   Pass 2 : [1, 2, 5, 3, 4]   <- 1, 2의 위치 확정
#   Pass 3 : [1, 2, 3, 5, 4]
#   Pass 4 : [1, 2, 3, 4, 5]


